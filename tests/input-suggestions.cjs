const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const script=fs.readFileSync(__dirname+'/../docs/index.html','utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const values=new Map(),c=vm.createContext({localStorage:{getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)},sessionStorage:{removeItem(){}},document:{querySelectorAll:()=>[]},window:{}});
vm.runInContext(script.slice(0,script.indexOf('function showSetup()')),c);
const run=s=>vm.runInContext(s,c);
values.set('ticket-management-event-suggestions-v1',JSON.stringify({titles:['過去のライブ','Ｆｏｏ','過去のライブ'],venues:['過去の会場','Hall']}));
run("data={lives:[{title:'共有中イベント',venue:'現在の会場'},{title:'Foo',venue:'Hall'}]}");
assert.deepEqual(Array.from(c.liveFieldOptions('title')),['過去のライブ','Ｆｏｏ','共有中イベント']);
assert.deepEqual(Array.from(c.liveFieldOptions('venue')),['過去の会場','Hall','現在の会場']);
assert.match(run("field('イベント名','title','', 'text',true,'event-title-options')"),/list="event-title-options"/);
assert.match(run("suggestionList('x',['<script>'])"),/&lt;script&gt;/);
c.modal=(title,body)=>{c.capturedBody=body};
c.liveForm();
assert.match(c.capturedBody,/list="event-title-options"/);
assert.match(c.capturedBody,/value="共有中イベント"/);
assert.match(c.capturedBody,/list="event-venue-options"/);
run("rememberEventInput(' 新規タイトル ',' 新しい会場 ')");
assert.equal(c.liveFieldOptions('title')[0],'新規タイトル');
assert.equal(c.liveFieldOptions('venue')[0],'新しい会場');
run("rememberEventInput('Ｆｏｏ','Hall')");
assert.equal(c.liveFieldOptions('title').filter(x=>x.normalize('NFKC').toLowerCase()==='foo').length,1);
assert.equal(c.liveFieldOptions('venue').filter(x=>x==='Hall').length,1);
run("localStorage.setItem('ticket-management-event-suggestions-v1','bad json')");
assert.deepEqual(Array.from(c.liveFieldOptions('title')),['共有中イベント','Foo']);
console.log('PASS: event title and venue suggestions combine saved history with shared events, normalize duplicates, retain editable inputs, escape options, and handle invalid storage');
